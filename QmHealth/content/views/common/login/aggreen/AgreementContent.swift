enum AgreementType: String, CaseIterable, Identifiable {
    case userAgreement = "user_agreement"
    case privacyPolicy = "privacy_policy"

    var id: String { rawValue }

    var title: String {
        switch self {
        case .userAgreement: return "用户协议"
        case .privacyPolicy: return "隐私政策"
        }
    }

    var updateDate: String {
        switch self {
        case .userAgreement: return "2026年09月04日"
        case .privacyPolicy: return "2026年09月04日"
        }
    }

    var sections: [AgreementSection] {
        switch self {
        case .userAgreement: return AgreementContent.userAgreementSections
        case .privacyPolicy: return AgreementContent.privacyPolicySections
        }
    }
}

